#!/usr/bin/env python3
"""Extend the pinned NumWorks catalogue with original Casio Chemistry revision notes."""
from pathlib import Path
import json
import re
root = Path(__file__).resolve().parents[1]
source = (root/'data/aqa_catalog_numworks_0.1.2-r1.inc').read_text()
data = json.loads((root/'data/chemistry_revision.json').read_text())
def literal(text): return json.dumps(text,ensure_ascii=True)
def bullets(lines): return '\n\n- '.join(lines)
def calls(body):
    position=0
    while m:=re.search(r'\b([SH])\(',body[position:]):
        start=position+m.start(); p=position+m.end(); begin=p; quoted=False; escaped=False; depth=1; args=[]
        while depth:
            c=body[p]
            if quoted:
                if escaped: escaped=False
                elif c=='\\': escaped=True
                elif c=='"': quoted=False
            elif c=='"': quoted=True
            elif c=='(': depth+=1
            elif c==')':
                depth-=1
                if depth==0: args.append(body[begin:p].strip())
            elif c==',' and depth==1: args.append(body[begin:p].strip()); begin=p+1
            p+=1
        yield start,p,m.group(1),args
        position=p

def expand(name,body):
    dataset=data[name]; seen=set(); parts=[]; previous=0
    for start,end,tier,args in calls(body):
        assert len(args)==3
        code,title=map(json.loads,args[:2]); seen.add(title)
        item=dataset['topics'][title]
        assert len(item['ideas'])>=2 and len(item['notes'])>=2
        heading=args[1]+(' " (higher only)"' if tier=='H' else '')
        parts += [body[previous:start],f'CHEM_NOTE({args[0]}, {heading}, {args[2]},\n      {literal(bullets(item["notes"]))},\n      {literal(bullets(item["ideas"]))})']
        previous=end
    parts.append(body[previous:])
    assert seen==set(dataset['topics']), (name,seen ^ set(dataset['topics']))
    result=''.join(parts)
    if name not in ['chem_changes','chem_key']:
        number={'chem_atoms':'4.1','chem_bonds':'4.2','chem_amount':'4.3','chem_energy':'4.5','chem_rates':'4.6','chem_organic':'4.7','chem_analysis':'4.8','chem_atmosphere':'4.9','chem_resources':'4.10','chem_practicals':'RP','chem_skills':'3'}[name]
        result='\n    CHEM_KEY('+literal(number)+', '+literal(bullets(dataset['key_ideas']))+'),'+result
    return result
pattern=r'(static const Topic )(chem_\w+)(\[\] = \{)(.*?)(\n\};)'
def replace(m):return m[1]+m[2]+m[3]+expand(m[2],m[4])+m[5]
source=re.sub(pattern,replace,source,flags=re.S)
# Keep the shared Biology/Physics skills untouched and supply Chemistry examples.
skills=re.search(r'static const Topic science_skills\[\] = \{(.*?)\n\};',source,re.S)
chem_skills='\n\nstatic const Topic chem_skills[] = {'+expand('chem_skills',skills[1])+'\n};'
source=source[:skills.end()]+chem_skills+source[skills.end():]
chapter=re.search(r'static const Chapter aqa_chemistry\[\] = \{(.*?)\n\};',source,re.S)
updated=chapter[0].replace('"Working scientifically and maths", science_skills','"Working scientifically and maths", chem_skills')
source=source[:chapter.start()]+updated+source[chapter.end():]
macros='''
/* Original topic-specific additions; generated by tools/generate_chemistry.py. */
#define CHEM_NOTE(id, heading, notes, extra, ideas) { .title = heading, .course = id "\\n\\nKey ideas\\n- " notes "\\n\\nDetailed explanation and examples\\n- " extra, .example = SCIENCE_MORE, .key_ideas = id "\\n\\n" heading "\\n\\nKey ideas\\n- " ideas }
#define CHEM_KEY(id, notes) { .title = "Key Ideas", .course = id "\\n\\nKey Ideas\\n- " notes }
'''
pos=source.index('\n\n',source.index('#define H'))
source=source[:pos]+ '\n'+macros+source[pos:]
source+='\n#undef CHEM_NOTE\n#undef CHEM_KEY\n'
(root/'src/aqa_catalog.inc').write_text(source)
print('Generated 151 individual expansions/key pages and 13 section summaries (including the two existing summary entries).')
